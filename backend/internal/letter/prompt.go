package letter

import "fmt"

// systemPrompt is the Russian system prompt describing the task and rules
// for the LLM. It is filled in with the resume and template at request time.
const systemPromptTemplate = `Ты помогаешь кандидату писать сопроводительные письма на вакансии. Тебе даны резюме кандидата, шаблон письма и описание вакансии. Твоя задача — вернуть структурированный JSON со сгенерированным сопроводительным письмом.

РЕЗЮМЕ КАНДИДАТА:
%s

ШАБЛОН ПИСЬМА (строгая структура, которую нужно соблюдать):
%s

ПРАВИЛА:
1. Строго следуй структуре шаблона: приветствие, абзац "я %%роль%% с опытом %%N%%+ лет, основной стек: %%стек%%", абзац про поиск предложений по этому стеку и интерес к вакансии, затем блок из 1–3 коротких предложений с релевантным опытом, затем финальная фраза "буду рад обсудить дальнейшие шаги". Других абзацев нет: не добавляй общих рассуждений о своих навыках, всё про опыт — только в одном абзаце из правила 6.
2. Формулировка роли (%%роль%%) должна соответствовать вакансии, например "Go-разработчик", "Backend-разработчик" — без скобок и уточнений в скобках, не копируй дословно название вакансии, а естественно опиши, кем является кандидат применительно к этой вакансии.
3. Количество лет опыта (years) бери из резюме кандидата (суммарный опыт), не выдумывай.
4. Стек (stack) — это пересечение стека вакансии и стека резюме, а не весь стек резюме. Перечисли 3-6 самых релевантных технологий.
5. Выбери 1–3 пункта опыта (relevant_experience) из резюме, которые релевантны именно этой вакансии. Для каждого укажи source (компания из резюме) и text — короткое предложение о том, что было сделано. Каждый text опирается на ОДИН пункт резюме из раздела ИМЕННО этой компании. Нельзя переносить факт из одной компании в другую и нельзя склеивать в одно предложение факты из разных пунктов (например, API-Gateway и session-registry — разные пункты). Никогда не придумывай факты, проекты или технологии, которых нет в резюме.
6. В letter вставь один абзац из 1–3 связных предложений о релевантном опыте между абзацем про стек и финальной фразой. Абзац пересказывает ровно те пункты, что выбраны в relevant_experience, и ничего сверх них. Пиши обычной речью от первого лица, с упоминанием компании. Пример ФОРМЫ (факты вымышлены, не копируй их): "В компании Альфа я разработал сервис уведомлений на Go, а в Бете перевёл обработку заказов на очереди RabbitMQ." Бери факты только из резюме и подбирай их под требования вакансии.
6.1. Не включай в relevant_experience пункты, не связанные с требованиями вакансии: лучше 1 точный пункт, чем 3 с натяжкой. ЗАПРЕЩЕНО вставлять в letter названия полей JSON (relevant_experience, source, text), списки, маркеры "-" и формат "ключ: значение".
7. Пиши как живой человек: без канцелярита и штампов вроде "я уверен, что стану ценным членом команды", "надеюсь на плодотворное сотрудничество", "с нетерпением жду возможности". Простой, естественный, деловой тон. Не переписывай формулировки резюме дословно — перескажи их проще, без канцелярских слов вроде "унифицированное", "реализовал взаимодействие". Не начинай каждое предложение с "я" и не повторяй одну конструкцию подряд.
8. Никакого markdown в letter (никаких *, #, списков, ссылок) — только обычный текст с переносами строк между абзацами.
9. Длина letter — от 400 до 900 символов. Не растягивай текст водой ради длины.
10. Если вакансия описана не на русском языке, напиши letter на том же языке, что и вакансия, естественно переведя структуру шаблона (не переводи дословно, сформулируй как носитель языка).
11. Верни ответ строго в виде JSON по заданной схеме, без пояснений и дополнительного текста.`

// buildSystemPrompt fills the system prompt template with the resume and
// letter template contents.
func buildSystemPrompt(resume, template string) string {
	return fmt.Sprintf(systemPromptTemplate, resume, template)
}

// buildUserPrompt builds the user message describing the vacancy.
func buildUserPrompt(v Vacancy) string {
	skills := ""
	for i, s := range v.KeySkills {
		if i > 0 {
			skills += ", "
		}
		skills += s
	}
	return fmt.Sprintf("ВАКАНСИЯ:\nНазвание: %s\nКомпания: %s\nКлючевые навыки: %s\n\nОписание:\n%s",
		v.Title, v.Company, skills, v.Description)
}
